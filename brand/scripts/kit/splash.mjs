// Splash and installer art, plus the Android 12+ splash icon and an
// animated-vector suggestion. Raster via sharp (already a brand dependency);
// nothing here needs a font — the wordmark is outlined.
import { glyph, tile, colour, motion } from '../../mark.mjs';
import { wordmark } from './common.mjs';

const gradient = (id) =>
  `<linearGradient id="${id}" x1="0.2" y1="0" x2="0.8" y2="1"><stop offset="0" stop-color="${colour.tileTop.hex}"/><stop offset="1" stop-color="${colour.tileBottom.hex}"/></linearGradient>`;
const tileAndLine = (v = glyph.master) =>
  `<rect x="${tile.x}" y="${tile.y}" width="${tile.size}" height="${tile.size}" rx="${tile.radius}" fill="url(#t)"/><path d="${v.d}" fill="none" stroke="#fff" stroke-width="${v.stroke}" stroke-linecap="round" stroke-linejoin="round"/>`;

/**
 * Night field, mark, optional wordmark. `markFrac` = mark edge / min(w, h);
 * `wordmarkBelow` stacks it (portrait), otherwise beside it (landscape).
 */
export function fieldSvg(w, h, { markFrac = 0.42, withWordmark = true, below = h > w } = {}) {
  const mpx = Math.min(w, h) * markFrac;
  const wmScale = (mpx * 0.38) / wordmark.capHeight;
  const wmW = wordmark.width * wmScale;
  const gap = mpx * 0.16;
  let mx;
  let my;
  let wx;
  let wy;
  if (!withWordmark) {
    mx = (w - mpx) / 2;
    my = (h - mpx) / 2;
  } else if (below) {
    mx = (w - mpx) / 2;
    my = h * 0.5 - mpx * 0.75;
    wx = (w - wmW) / 2;
    wy = my + mpx + gap + wordmark.capHeight * wmScale;
  } else {
    const total = mpx + gap + wmW;
    mx = (w - total) / 2;
    my = (h - mpx) / 2;
    wx = mx + mpx + gap;
    wy = h / 2 + (wordmark.capHeight * wmScale) / 2;
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
<defs>${gradient('t')}<radialGradient id="glow" cx="0.5" cy="0.45" r="0.75"><stop offset="0" stop-color="${colour.nightRaised.hex}"/><stop offset="1" stop-color="${colour.night.hex}"/></radialGradient></defs>
<rect width="${w}" height="${h}" fill="url(#glow)"/>
<g transform="translate(${mx} ${my}) scale(${mpx / 48})">${tileAndLine()}</g>
${withWordmark ? `<path transform="translate(${wx} ${wy}) scale(${wmScale})" fill="${colour.paper.hex}" d="${wordmark.d}"/>` : ''}</svg>`;
}

/** Android 12+ splash icon: 288 dp canvas, content inside the 192 dp circle. */
export function androidSplashSvg(px, { plate = true, guide = false } = {}) {
  const dp = px / 288;
  const circle = 192 * dp;
  // Tile diagonal must fit the circle: edge ≤ circle / √2. Tile is 42/48 of the mark box.
  const tileEdge = (circle / Math.SQRT2) * 0.98;
  const box = (tileEdge * 48) / 42;
  const off = (px - box) / 2;
  const content = plate
    ? tileAndLine()
    : `<path d="${glyph.master.d}" fill="none" stroke="#fff" stroke-width="${glyph.master.stroke}" stroke-linecap="round" stroke-linejoin="round"/>`;
  const overlay = guide ? `<rect width="${px}" height="${px}" fill="${colour.night.hex}"/>` : '';
  const marks = guide
    ? `<circle cx="${px / 2}" cy="${px / 2}" r="${circle / 2}" fill="none" stroke="${colour.signal.hex}" stroke-width="${2 * dp}" stroke-dasharray="${8 * dp} ${6 * dp}"/><rect x="1" y="1" width="${px - 2}" height="${px - 2}" fill="none" stroke="#ffffff" stroke-opacity="0.4" stroke-width="${2 * dp}"/>`
    : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="0 0 ${px} ${px}"><defs>${gradient('t')}</defs>${overlay}<g transform="translate(${off} ${off}) scale(${box / 48})">${content}</g>${marks}</svg>`;
}

/**
 * AnimatedVectorDrawable: tile settles and the line draws, the app's intro.
 * 288 dp viewport so it drops into windowSplashScreenAnimatedIcon as is.
 * Duration ≤ 1000 ms, which Android 12 caps the splash animation at.
 */
export function androidAvd() {
  const s = (192 / Math.SQRT2 / 42) * 0.98; // grid unit → dp, tile diagonal inside the 192 dp circle
  const t = 144 - 24 * s;
  const tileMs = Math.round(motion.intro.ms * 0.55);
  const drawMs = Math.round(motion.intro.ms * 0.7);
  const delay = Math.round(motion.intro.ms * 0.3);
  const interp = (id) =>
    `<aapt:attr name="android:interpolator"><pathInterpolator android:pathData="M0,0 C${motion.ease
      .match(/[\d.]+/g)
      .slice(0, 2)
      .join(',')} ${motion.ease
      .match(/[\d.]+/g)
      .slice(2)
      .join(',')} 1,1"/></aapt:attr><!-- ${id} -->`;
  return `<?xml version="1.0" encoding="utf-8"?>
<!--
  Vitals splash: the mark's intro (tile settles, line draws), for Android 12+
  windowSplashScreenAnimatedIcon. A SUGGESTION from the brand kit — not wired
  into apps/android. Generated by brand/scripts/kit.mjs from brand/mark.mjs.
  Use with windowSplashScreenBackground = ${colour.night.hex} and
  windowSplashScreenAnimationDuration = ${motion.intro.ms}.
-->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
        <vector
            android:width="288dp"
            android:height="288dp"
            android:viewportWidth="288"
            android:viewportHeight="288">
            <group android:name="mark" android:translateX="${t.toFixed(3)}" android:translateY="${t.toFixed(3)}" android:scaleX="${s.toFixed(4)}" android:scaleY="${s.toFixed(4)}">
                <group android:name="tile" android:pivotX="24" android:pivotY="24">
                    <path android:name="tileFill" android:pathData="M13,3h22a10,10 0,0 1,10 10v22a10,10 0,0 1,-10 10h-22a10,10 0,0 1,-10 -10v-22a10,10 0,0 1,10 -10z">
                        <aapt:attr name="android:fillColor">
                            <gradient android:type="linear" android:startX="11.4" android:startY="3" android:endX="36.6" android:endY="45">
                                <item android:offset="0" android:color="#FF${colour.tileTop.hex.slice(1)}" />
                                <item android:offset="1" android:color="#FF${colour.tileBottom.hex.slice(1)}" />
                            </gradient>
                        </aapt:attr>
                    </path>
                </group>
                <path
                    android:name="line"
                    android:fillColor="#00000000"
                    android:strokeColor="#FFFFFFFF"
                    android:strokeWidth="${glyph.master.stroke}"
                    android:strokeLineCap="round"
                    android:strokeLineJoin="round"
                    android:trimPathEnd="0"
                    android:pathData="${glyph.master.d}" />
            </group>
        </vector>
    </aapt:attr>
    <target android:name="tile">
        <aapt:attr name="android:animation">
            <set>
                <objectAnimator android:propertyName="scaleX" android:duration="${tileMs}" android:valueFrom="${motion.intro.tileFrom}" android:valueTo="1" android:valueType="floatType">${interp('scaleX')}</objectAnimator>
                <objectAnimator android:propertyName="scaleY" android:duration="${tileMs}" android:valueFrom="${motion.intro.tileFrom}" android:valueTo="1" android:valueType="floatType">${interp('scaleY')}</objectAnimator>
            </set>
        </aapt:attr>
    </target>
    <target android:name="tileFill">
        <aapt:attr name="android:animation">
            <objectAnimator android:propertyName="fillAlpha" android:duration="${tileMs}" android:valueFrom="0" android:valueTo="1" android:valueType="floatType">${interp('fillAlpha')}</objectAnimator>
        </aapt:attr>
    </target>
    <target android:name="line">
        <aapt:attr name="android:animation">
            <objectAnimator android:propertyName="trimPathEnd" android:startOffset="${delay}" android:duration="${drawMs}" android:valueFrom="0" android:valueTo="1" android:valueType="floatType">${interp('trimPathEnd')}</objectAnimator>
        </aapt:attr>
    </target>
</animated-vector>
`;
}

/** 24-bit bottom-up BMP from raw RGB — NSIS (MUI2) wants BMP for its header and sidebar. */
export function bmp(raw, w, h, channels) {
  const rowBytes = Math.ceil((w * 3) / 4) * 4;
  const size = 54 + rowBytes * h;
  const b = Buffer.alloc(size);
  b.write('BM', 0, 'ascii');
  b.writeUInt32LE(size, 2);
  b.writeUInt32LE(54, 10);
  b.writeUInt32LE(40, 14);
  b.writeInt32LE(w, 18);
  b.writeInt32LE(h, 22);
  b.writeUInt16LE(1, 26);
  b.writeUInt16LE(24, 28);
  b.writeUInt32LE(rowBytes * h, 34);
  b.writeInt32LE(2835, 38);
  b.writeInt32LE(2835, 42);
  for (let y = 0; y < h; y++) {
    const row = 54 + (h - 1 - y) * rowBytes;
    for (let x = 0; x < w; x++) {
      const i = (y * w + x) * channels;
      b[row + x * 3] = raw[i + 2];
      b[row + x * 3 + 1] = raw[i + 1];
      b[row + x * 3 + 2] = raw[i];
    }
  }
  return b;
}
